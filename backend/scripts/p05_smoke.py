"""P-05 live smoke: boots the real application under uvicorn and drives
Scenarios A, B, D, F and J over HTTP against it. Run:

    .venv/bin/python scripts/p05_smoke.py

Writes a transcript to docs/reports/P05_SMOKE_EVIDENCE.txt (relative to
the repository root). Uses a throwaway data directory; nothing persists.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import httpx

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
import random
PORT = random.randint(20000, 45000)  # fresh port per run: no stale servers
BASE = f"http://127.0.0.1:{PORT}/api/v1"

LINES: list[str] = []


def log(line: str = "") -> None:
    print(line)
    LINES.append(line)


def show(title: str, response: httpx.Response, keys: tuple[str, ...] = ()) -> dict:
    data = response.json().get("data") or {}
    picked = {k: data.get(k) for k in keys} if keys else data
    log(f"[{title}] HTTP {response.status_code} -> {json.dumps(picked, default=str)[:600]}")
    return data


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="p05-smoke-"))
    env = dict(os.environ)
    env.update({
        "AUTONOMUS_MODE": "controlled",
        "AUTONOMUS_DATA_DIR": str(tmp / "data"),
        "AUTONOMUS_DATABASE_URL": f"sqlite:///{tmp}/smoke.db",
        "AUTONOMUS_ADMIN_PASSWORD": "smoke-owner-password-123",
        "AUTONOMUS_AUTO_MIGRATE": "true",
        # Same admission setting the test-suite uses: this shared VM runs
        # at >90% RAM, and the P-01 monitor would otherwise (correctly)
        # queue nonessential agent creation. Noted in the transcript.
        "AUTONOMUS_BLOCK_NONESSENTIAL_ON_THRESHOLD": "false",
        "TMPDIR": "/tmp",
    })
    proc = subprocess.Popen(
        [sys.executable, "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1",
         "--port", str(PORT)],
        cwd=BACKEND, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    client = httpx.Client(base_url=BASE, timeout=30, trust_env=False)
    try:
        for _ in range(60):
            try:
                if client.get("/health/live").status_code == 200:
                    break
            except httpx.HTTPError:
                pass
            time.sleep(0.5)
        log("=== AUTONOMUS P-05 SMOKE (real uvicorn, controlled mode) ===")
        log(f"server: {BASE}  data_dir: {tmp}/data")
        log("note: AUTONOMUS_BLOCK_NONESSENTIAL_ON_THRESHOLD=false (test-suite "
            "setting; this VM's RAM pressure would otherwise queue agent creation)")

        login = client.post("/auth/login", json={
            "username": "owner", "password": "smoke-owner-password-123"})
        token = login.json()["data"]["access_token"]
        auth = {"Authorization": f"Bearer {token}"}
        log(f"[login] HTTP {login.status_code} (owner session established)")

        report = show("health-report", client.get("/execution/health-report", headers=auth))
        log(f"  code_isolation: {report['code_isolation']}")
        log(f"  browser_backend: {report['browser_backend']}")
        log(f"  desktop_adapter: {report['desktop_adapter']}")
        for tool in report["tools"]:
            log(f"  tool {tool['tool']:<12} registry={tool['registry_status']:<10} "
                f"health={tool['health_status']}")

        created = client.post("/agent-factory/create", headers=auth,
                              json={"role": "research_agent"})
        log(f"[agent create raw] HTTP {created.status_code} -> "
            f"{created.text[:400]}")
        agent_id = created.json()["data"]["created_agent_id"]
        log(f"[agent] Research Agent created: {agent_id}")

        def grant(capability: str) -> None:
            resp = client.post(f"/agents/{agent_id}/permissions/request",
                               headers=auth, json={"capability": capability})
            data = resp.json()["data"]
            if data.get("status") == "approval_required":
                client.post(f"/agents/{agent_id}/permissions/approve", headers=auth,
                            json={"approval_id": data["approval_id"], "approve": True})
            log(f"[grant] {capability} granted via the P-04 governed flow")

        grant("file_read")
        grant("file_write")
        grant("sandboxed_code_execution")
        grant("api_write")

        # ---------------- Scenario A: report created, hash-verified, evidence
        log("\n--- Scenario A: Research Agent report ---")
        ws = f"agent:{agent_id}"
        created_doc = show("A create report", client.post(
            "/execution/documents/create_text", headers=auth, json={
                "agent_id": agent_id,
                "parameters": {"workspace": ws, "path": "reports/smoke-report.md",
                               "content": "# Smoke Report\n\nGenerated by P-05."},
                "expected_outcome": {"file": {"workspace": ws,
                                              "path": "reports/smoke-report.md",
                                              "content_contains": "Smoke Report"}}}),
            ("status", "verification_status", "result_summary"))
        evidence = client.get(f"/execution/requests/{created_doc['id']}/evidence",
                              headers=auth).json()["data"]
        log(f"  evidence recorded: {len(evidence)} record(s), "
            f"sha256={evidence[0]['content_hash'][:16]}…")

        # ---------------- Scenario B: approved Python under limits
        log("\n--- Scenario B: controlled Python execution ---")
        ran = show("B code run", client.post("/execution/code/run", headers=auth, json={
            "agent_id": agent_id,
            "parameters": {"code": "print('smoke total', sum(range(10)))"},
            "expected_outcome": {"output_contains": "smoke total 45", "exit_code": 0}}),
            ("status", "verification_status", "result_summary"))
        runs = client.get(f"/execution/requests/{ran['id']}", headers=auth).json()["data"]["runs"]
        output = runs[0]["result"]["output"]
        log(f"  stdout={output['stdout'].strip()!r} isolation={output['isolation']} "
            f"workspace_cleaned={output['workspace_cleaned']}")
        code_runs = tmp / "data" / "execution_workspaces" / "temporary" / "code_runs"
        leftovers = list(code_runs.iterdir()) if code_runs.exists() else []
        log(f"  cleanup verified on disk: leftover run dirs = {len(leftovers)}")

        # ---------------- Scenario F: traversal rejected + security event
        log("\n--- Scenario F: filesystem attack ---")
        attack = show("F traversal", client.post("/execution/files/read", headers=auth,
                                                 json={
                                                     "agent_id": agent_id,
                                                     "parameters": {
                                                         "workspace": ws,
                                                         "path": "../../etc/passwd"}}),
                      ("status", "error_category", "result_summary"))
        audit = client.get(f"/execution/requests/{attack['id']}/audit",
                           headers=auth).json()["data"]
        log(f"  audit entries for the attack request: {len(audit)} "
            f"(actions: {[a['action'] for a in audit]})")

        # ---------------- Scenario D: sensitive action held for approval
        log("\n--- Scenario D: sensitive action approval hold ---")
        client.patch("/execution/settings", headers=auth,
                     json={"values": {"api_allowlist": ["api.example.com"]}})
        held = client.post("/execution/requests", headers=auth, json={
            "agent_id": agent_id, "tool": "api_http", "action": "post",
            "parameters": {"url": "https://api.example.com/items", "body": "{}"}})
        held_data = show("D submit POST", held, ("status", "approval_id", "risk_level"))
        attempt = client.post(f"/execution/requests/{held_data['id']}/execute",
                              headers=auth)
        log(f"[D execute before approval] HTTP {attempt.status_code} -> "
            f"{attempt.json()['error']['code']}: {attempt.json()['error']['message'][:90]}")
        detail = client.get(f"/execution/requests/{held_data['id']}",
                            headers=auth).json()["data"]
        log(f"  runs before approval: {len(detail['runs'])} (nothing executed)")
        approval = client.get(f"/approvals/{held_data['approval_id']}",
                              headers=auth).json()["data"]
        log(f"  owner inspects approval: action={approval['action']} "
            f"resource={approval['resource']} status={approval['status']}")
        client.post(f"/approvals/{held_data['approval_id']}/decision", headers=auth,
                    json={"approve": True})
        executed = show("D execute after approval", client.post(
            f"/execution/requests/{held_data['id']}/execute", headers=auth),
            ("status", "error_category", "result_summary"))
        log("  (post-approval the gate opens; in this sandbox the live fetch to "
            "api.example.com is whatever the network returns — the gate behaviour "
            "is the demonstrated fact)")

        # ---------------- Scenario J: emergency stop
        log("\n--- Scenario J: emergency execution stop ---")
        stop = show("J emergency-stop", client.post("/execution/emergency-stop",
                                                    headers=auth))
        blocked = show("J submit during stop", client.post(
            "/execution/files/list", headers=auth, json={
                "agent_id": agent_id,
                "parameters": {"workspace": "shared", "path": ""}}),
            ("status", "result_summary"))
        resumed = show("J emergency-resume", client.post(
            "/execution/emergency-resume", headers=auth))
        after = show("J submit after resume", client.post(
            "/execution/files/list", headers=auth, json={
                "agent_id": agent_id,
                "parameters": {"workspace": "shared", "path": ""}}),
            ("status",))
        status = show("status/metrics", client.get("/execution/status", headers=auth))
        log(f"  requests by status: {status['requests_by_status']}")
        log("\n=== SMOKE COMPLETE ===")
        return 0
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        out = REPO / "docs" / "reports" / "P05_SMOKE_EVIDENCE.txt"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(LINES) + "\n", encoding="utf-8")
        print(f"transcript written to {out}")


if __name__ == "__main__":
    raise SystemExit(main())
