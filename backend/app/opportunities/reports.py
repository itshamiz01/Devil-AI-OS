"""P-03 §23 opportunity report generation.

Nine sections, A to I, always present - including when there is nothing to put in
them.  An empty section that says "no verified evidence was obtained" is a finding;
an omitted section is a gap the reader cannot see.

The report carries an ``is_test_data`` flag which defaults to True and cannot be
cleared without an explicit, justified call.  That is the mechanism behind §31's
requirement that sample reports use clearly labelled test data and are never
presented as real market research.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime, timezone
from typing import Any

from app.opportunities.schemas import (
    BusinessModelAnalysis,
    CompetitorAssessment,
    CommercialAssessment,
    DistributionAssessment,
    EvidenceClassification,
    FinalClassification,
    MarketAssessment,
    Opportunity,
    OpportunityScore,
    OpportunityState,
    ReportSection,
    RiskAssessment,
    ScoringOutcome,
    SourceEvidence,
    ValidationAssessment,
)
from app.opportunities.validation import LEVEL_REQUIREMENTS

__all__ = ["NO_EVIDENCE_STATEMENT", "ReportGenerator", "TEST_DATA_NOTICE"]

#: The exact wording used when a section has nothing verified to report.  Kept as
#: a constant so the phrase is consistent across every report and greppable in an
#: audit.
NO_EVIDENCE_STATEMENT = (
    "Insufficient verified evidence. No admissible evidence was obtained for this "
    "section, so nothing is asserted here."
)

TEST_DATA_NOTICE = (
    "SYNTHETIC TEST DATA - NOT REAL MARKET RESEARCH. Every figure, listing, price "
    "and observation in this report comes from mock fixtures built to exercise the "
    "pipeline. None of it was acquired from a live source and none of it describes "
    "a real market."
)


class ReportGenerator:
    """Builds the nine-section report for one opportunity."""

    def __init__(self, *, test_data_notice: str = TEST_DATA_NOTICE):
        self.test_data_notice = test_data_notice

    # ------------------------------------------------------------------ #
    def _money(self, value: Any, currency: str) -> str:
        return f"{value} {currency}" if value is not None else "unknown"

    def section_a(
        self,
        opportunity: Opportunity,
        outcome: ScoringOutcome | None,
        *,
        currency: str,
    ) -> str:
        lines = [
            f"# A. Executive summary",
            "",
            f"**Opportunity:** {opportunity.candidate.title}",
            f"**Category:** {opportunity.candidate.category.value.replace('_', ' ')}",
            f"**Discovery method:** {opportunity.candidate.discovery_method.value.replace('_', ' ')}",
            f"**Lifecycle state:** {opportunity.state.value.replace('_', ' ')}",
        ]
        if outcome is None:
            lines += [
                "",
                "**Final classification:** NOT SCORED",
                "",
                NO_EVIDENCE_STATEMENT,
            ]
            return "\n".join(lines)
        lines += [
            "",
            f"**Final classification:** {outcome.final_classification.value.replace('_', ' ').upper()}",
            f"**Recommendable:** {'yes' if outcome.recommendable else 'no'}",
            f"**Attractiveness (0-5, weighted):** {outcome.score.attractiveness}",
            f"**Evidence quality (0-5, reported separately):** {outcome.score.evidence_quality}",
            f"**Evidence coverage of the scoring dimensions:** {outcome.score.coverage_pct}%",
            f"**Validation level reached:** {opportunity.validation.level.value} "
            f"({opportunity.validation.level.name})",
        ]
        if outcome.hard_rejections:
            lines += ["", "**Hard rejections (these override the score):**"]
            lines += [f"- {r}" for r in outcome.hard_rejections]
        if outcome.reasons:
            lines += ["", "**Reasoning:**"]
            lines += [f"- {r}" for r in outcome.reasons]
        if opportunity.assumptions:
            lines += ["", "**Assumptions this conclusion rests on:**"]
            lines += [f"- {a.statement} (basis: {a.basis.value}, sensitivity: {a.sensitivity})" for a in opportunity.assumptions]
        return "\n".join(lines)

    def section_b(self, opportunity: Opportunity) -> str:
        c = opportunity.candidate
        lines = [
            "# B. Opportunity description",
            "",
            f"**Title:** {c.title}",
            f"**Description:** {c.description}",
            f"**Business category:** {c.category.value.replace('_', ' ')}",
            f"**Discovery method:** {c.discovery_method.value.replace('_', ' ')}",
            f"**Derived from:** {c.derived_from or 'not recorded'}",
            f"**Generated by:** {c.generated_by}",
            f"**Target customer:** {c.target_customer or 'not established'}",
            f"**Problem addressed:** {c.problem_addressed or 'not established'}",
            f"**Proposed offering:** {c.proposed_offering or 'not established'}",
        ]
        if opportunity.budget is not None:
            lines += [
                "",
                "**Owner budget constraint:**",
                f"- available capital: {opportunity.budget.available_capital} {opportunity.budget.currency}",
                f"- band: {opportunity.budget.band.value}",
                f"- stated by owner: {'yes' if opportunity.budget.owner_stated else 'no'}",
            ]
        else:
            lines += ["", "**Owner budget constraint:** not supplied"]
        return "\n".join(lines)

    def section_c(self, market: MarketAssessment | None) -> str:
        if market is None:
            return "\n".join(["# C. Market analysis", "", NO_EVIDENCE_STATEMENT])
        lines = [
            "# C. Market analysis",
            "",
            f"**Verdict:** {market.verdict.replace('_', ' ')}",
            f"**Demand evidence level:** {market.demand_evidence_level.value}",
            f"**Problem importance:** {market.problem_importance}"
            + (f" - {market.problem_importance_basis}" if market.problem_importance_basis else ""),
        ]
        if market.reasons:
            lines += ["", "**Basis:**"] + [f"- {r}" for r in market.reasons]
        sizing = market.sizing
        if sizing is not None:
            lines += ["", "**Market sizing (TAM / SAM / SOM):**"]
            for label, level in (("TAM", sizing.tam), ("SAM", sizing.sam), ("SOM", sizing.som)):
                if level is None or level.value is None:
                    lines.append(f"- {label}: unknown - no admissible evidence carries a figure")
                else:
                    lines.append(
                        f"- {label}: {level.value} {level.currency} per year "
                        f"(provenance: {level.provenance.value}; basis: {level.basis}; "
                        f"evidence: {', '.join(level.evidence_ids)})"
                    )
            lines.append(f"- geography: {', '.join(sizing.geography) or 'not supplied'}")
            lines.append(f"- customer segments: {', '.join(sizing.customer_segments) or 'not supplied'}")
        if market.signals:
            lines += ["", "**Demand signals observed:**"]
            for signal in market.signals[:12]:
                value = (
                    f"{signal.metric_value} {signal.unit or ''}".strip()
                    if signal.metric_value is not None
                    else "no value"
                )
                lines.append(
                    f"- {signal.signal[:120]} [{value}; provenance {signal.provenance.value}; "
                    f"evidence {signal.evidence_id or 'none'}]"
                )
        else:
            lines += ["", "**Demand signals observed:** none"]
        if market.willingness_indicators:
            lines += ["", "**Willingness-to-pay indicators:**"] + [f"- {w}" for w in market.willingness_indicators]
        if market.data_gaps:
            lines += ["", "**Data gaps:**"] + [f"- {g}" for g in market.data_gaps]
        return "\n".join(lines)

    def section_d(self, competitors: CompetitorAssessment | None) -> str:
        if competitors is None:
            return "\n".join(["# D. Competitive analysis", "", NO_EVIDENCE_STATEMENT])
        lines = [
            "# D. Competitive analysis",
            "",
            f"**Verdict:** {competitors.verdict.replace('_', ' ')}",
            f"**Market saturation:** {competitors.market_saturation}",
            f"**Competitors observed:** {len(competitors.competitors)} "
            f"({competitors.inspected_count} inspected)",
        ]
        if competitors.price_range_low is not None:
            lines.append(
                f"**Observed price range:** {competitors.price_range_low} to "
                f"{competitors.price_range_high}"
            )
        else:
            lines.append("**Observed price range:** unknown - no quoted competitor price")
        if competitors.competitors:
            lines += ["", "**Competitors:**"]
            for c in competitors.competitors[:15]:
                prices = ", ".join(str(p) for p in c.price_points) or "no price observed"
                lines.append(
                    f"- {c.name} ({prices}; provenance {c.pricing_provenance.value}; "
                    f"inspected {'yes' if c.inspected else 'no'})"
                )
        if competitors.gaps_identified:
            lines += ["", "**Gaps identified:**"] + [f"- {g}" for g in competitors.gaps_identified]
        else:
            lines += ["", "**Gaps identified:** none"]
        if competitors.differentiation_available:
            lines += ["", f"**Differentiation available:** {competitors.differentiation_basis}"]
        if competitors.reasons:
            lines += ["", "**Basis:**"] + [f"- {r}" for r in competitors.reasons]
        if competitors.data_gaps:
            lines += ["", "**Data gaps:**"] + [f"- {g}" for g in competitors.data_gaps]
        return "\n".join(lines)

    def section_e(self, model: BusinessModelAnalysis | None) -> str:
        if model is None:
            return "\n".join(
                [
                    "# E. Business model",
                    "",
                    NO_EVIDENCE_STATEMENT,
                    "",
                    "No business model could be derived: no competitor price was "
                    "observed and no revenue mechanism was supplied. Inventing one "
                    "here would make every downstream financial figure meaningless.",
                ]
            )
        lines = [
            "# E. Business model",
            "",
            f"**Model type:** {model.model_type.value.replace('_', ' ')}",
            f"**Revenue mechanism:** {model.revenue_mechanism}",
            f"**Billing period:** {model.billing_period}",
            f"**Price point:** {self._money(model.price_point, 'USD')} "
            f"(provenance: {model.price_provenance.value})",
        ]
        if model.processor_fee_pct is not None:
            lines.append(
                f"**Payment processor:** {model.payment_processor or 'unspecified'} at "
                f"{model.processor_fee_pct}% (provenance: {model.fee_provenance.value})"
            )
        else:
            lines.append("**Payment processor fee:** unknown")
        if model.lifetime_value is not None:
            lines.append(
                f"**Estimated lifetime value:** {self._money(model.lifetime_value, 'USD')} "
                f"(provenance: {model.ltv_provenance.value})"
            )
        if model.weaknesses:
            lines += ["", "**Model weaknesses:**"] + [f"- {w}" for w in model.weaknesses]
        if model.evidence_ids:
            lines += ["", f"**Evidence:** {', '.join(model.evidence_ids)}"]
        return "\n".join(lines)

    def section_f(self, commercial: CommercialAssessment | None, *, currency: str) -> str:
        if commercial is None:
            return "\n".join(["# F. Commercial feasibility", "", NO_EVIDENCE_STATEMENT])
        lines = [
            "# F. Commercial feasibility",
            "",
            f"**Verdict:** {commercial.verdict.replace('_', ' ')}",
            f"**Viable:** {'yes' if commercial.viable else 'no'}",
            f"**Affordable within the owner's stated budget:** {'yes' if commercial.affordable else 'no'}",
            "",
            "**Cost structure:**",
            f"- startup total: {self._money(commercial.costs.startup_total(), currency)}",
            f"- recurring monthly total: {self._money(commercial.costs.recurring_monthly_total(), currency)}",
            f"- variable cost per unit: {self._money(commercial.costs.variable_per_unit_total(), currency)}",
            f"- cost lines: {len(commercial.costs.items)}",
            f"- provenance breakdown: "
            + ", ".join(f"{k}={v}" for k, v in commercial.costs.provenance_counts().items() if v),
        ]
        if commercial.unpriced_cost_items:
            lines.append(
                f"- **UNPRICED cost lines:** {', '.join(commercial.unpriced_cost_items)}. "
                "These are unknown, not zero, and the verdict cannot be 'viable' while "
                "they remain unpriced."
            )
        lines += ["", "**Cost lines:**"]
        for item in commercial.costs.items:
            lines.append(
                f"- {item.name}: {self._money(item.amount, item.currency)} "
                f"({item.kind}, {item.billing_period}, provenance {item.provenance.value}"
                + (f", evidence {item.evidence_id}" if item.evidence_id else "")
                + (f", assumption: {item.assumption}" if item.assumption else "")
                + ")"
            )
        if commercial.scenarios:
            lines += [
                "",
                "**Scenarios (only volume varies; costs and price are held constant):**",
                "",
                "| scenario | volume factor | units | revenue | variable cost | gross profit | contribution margin | operating profit | net cash flow |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
            for s in commercial.scenarios:
                p = s.projection
                lines.append(
                    f"| {s.name.value} | {s.volume_factor} | {p.units_sold} | "
                    f"{p.revenue} | {p.variable_cost} | {p.gross_profit} | "
                    f"{p.contribution_margin if p.contribution_margin is not None else 'n/a'} | "
                    f"{p.operating_profit} | {p.net_cash_flow} |"
                )
        if commercial.break_even is not None:
            be = commercial.break_even
            lines += [
                "",
                "**Break-even:**",
                f"- contribution per unit: {be.contribution_per_unit}",
                f"- monthly break-even units: "
                + (str(be.monthly_break_even_units) if be.monthly_break_even_units is not None else "not achievable"),
                f"- units to recover startup: "
                + (str(be.units_to_recover_startup) if be.units_to_recover_startup is not None else "not achievable"),
                f"- months to recover startup: "
                + (str(be.months_to_recover_startup) if be.months_to_recover_startup is not None else "not achievable"),
                f"- achievable: {'yes' if be.achievable else 'NO'}"
                + (f" - {be.reason}" if be.reason else ""),
            ]
        if commercial.budget_compatibility is not None:
            bc = commercial.budget_compatibility
            lines += [
                "",
                "**Budget compatibility:**",
                f"- owner's stated capital: {self._money(bc.available_capital, currency)}",
                f"- required startup: {self._money(bc.required_startup, currency)}",
                f"- required first-period cash: {self._money(bc.required_first_period_cash, currency)}",
                f"- verdict: {bc.verdict.replace('_', ' ')}",
                f"- shortfall: {self._money(bc.shortfall, currency)}",
                f"- **the owner's budget was modified: {'yes' if bc.budget_was_modified else 'no'}**",
            ]
            if bc.reason:
                lines.append(f"- note: {bc.reason}")
        if commercial.reasons:
            lines += ["", "**Reasoning:**"] + [f"- {r}" for r in commercial.reasons]
        if commercial.assumptions:
            lines += ["", "**Assumptions:**"] + [
                f"- {a.statement} (basis: {a.basis.value}, sensitivity: {a.sensitivity})"
                for a in commercial.assumptions
            ]
        return "\n".join(lines)

    def section_g(self, distribution: DistributionAssessment | None) -> str:
        if distribution is None:
            return "\n".join(["# G. Distribution and acquisition", "", NO_EVIDENCE_STATEMENT])
        lines = [
            "# G. Distribution and acquisition",
            "",
            f"**Verdict:** {distribution.verdict.replace('_', ' ')}",
            f"**Reachable without paid advertising:** {'yes' if distribution.reachable_without_paid_ads else 'no'}",
            f"**Platform dependency risk:** {distribution.platform_dependency_risk.value}",
        ]
        if distribution.channels:
            lines += ["", "**Channels:**"]
            for c in distribution.channels[:15]:
                lines.append(
                    f"- {c.channel} ({c.kind}, platform-controlled "
                    f"{'yes' if c.platform_controlled else 'no'}, dependency {c.dependency_risk}, "
                    f"cost provenance {c.cost_provenance.value})"
                )
        else:
            lines += ["", "**Channels:** none observed"]
        if distribution.reasons:
            lines += ["", "**Basis:**"] + [f"- {r}" for r in distribution.reasons]
        if distribution.data_gaps:
            lines += ["", "**Data gaps:**"] + [f"- {g}" for g in distribution.data_gaps]
        return "\n".join(lines)

    def section_h(self, risk: RiskAssessment | None) -> str:
        if risk is None:
            return "\n".join(
                [
                    "# H. Risk and compliance",
                    "",
                    NO_EVIDENCE_STATEMENT,
                    "",
                    "Note that an unassessed compliance position is not a cleared one. "
                    "Without a target jurisdiction the engine reports "
                    "'cannot determine' rather than 'acceptable'.",
                ]
            )
        lines = [
            "# H. Risk and compliance",
            "",
            f"**Verdict:** {risk.verdict.replace('_', ' ')}",
            f"**Blocked:** {'YES' if risk.blocked else 'no'}",
            f"**Highest severity:** {risk.highest_severity.value}",
            f"**Jurisdictions considered:** {', '.join(risk.jurisdictions_considered) or 'none supplied'}",
        ]
        if risk.prohibited_category_matched:
            lines += [
                "",
                f"**PROHIBITED CATEGORY MATCHED:** {risk.prohibited_category_matched}",
                "",
                "This is a hard rejection. It cannot be outweighed by any score, "
                "any market size or any profit projection.",
            ]
        if risk.findings:
            lines += ["", "**Findings:**"]
            for f in risk.findings:
                lines.append(
                    f"- [{f.severity.value.upper()}] ({f.category.replace('_', ' ')}) "
                    f"{f.description}"
                    + (f" | mitigation: {f.mitigation}" if f.mitigation else "")
                    + (f" | jurisdiction: {f.jurisdiction}" if f.jurisdiction else "")
                    + (f" | platform: {f.platform}" if f.platform else "")
                )
        else:
            lines += ["", "**Findings:** none"]
        if risk.reasons:
            lines += ["", "**Reasoning:**"] + [f"- {r}" for r in risk.reasons]
        if risk.data_gaps:
            lines += ["", "**Data gaps:**"] + [f"- {g}" for g in risk.data_gaps]
        return "\n".join(lines)

    def section_i(
        self,
        evidence: Sequence[SourceEvidence],
        validation: ValidationAssessment,
        score: OpportunityScore | None,
        *,
        refusals: Sequence[dict[str, Any]] = (),
    ) -> str:
        lines = [
            "# I. Evidence and validation",
            "",
            f"**Validation level reached:** {validation.level.value} - {validation.level.name}",
            f"**What that level requires:** {LEVEL_REQUIREMENTS[validation.level]}",
        ]
        if validation.next_level is not None:
            lines += [
                f"**Next level:** {validation.next_level.value} - {validation.next_level.name}",
                f"**What it would require:** {validation.next_level_requirement}",
            ]
        if validation.satisfied_inputs:
            lines += ["", "**Inputs that satisfied the level:**"] + [f"- {i}" for i in validation.satisfied_inputs]
        if validation.rejected_inputs:
            lines += [
                "",
                "**Inputs rejected as a basis for validation (§18 prohibitions):**",
            ] + [f"- {i}" for i in validation.rejected_inputs]
        if validation.blocking_prohibition:
            lines += ["", f"**Blocking prohibition:** {validation.blocking_prohibition}"]
        lines += ["", f"**Evidence records: {len(evidence)}**"]
        if evidence:
            counts: dict[str, int] = {}
            for item in evidence:
                counts[item.classification.value] = counts.get(item.classification.value, 0) + 1
            lines.append(
                "- by classification: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items()))
            )
            lines += ["", "| id | type | classification | reliability | source | claim |", "|---|---|---|---|---|---|"]
            for item in evidence[:40]:
                lines.append(
                    f"| {item.evidence_id} | {item.evidence_type.value} | "
                    f"{item.classification.value} | {item.reliability.value} | "
                    f"{item.source_id or 'none'} | {item.claim[:80]} |"
                )
        else:
            lines.append("- " + NO_EVIDENCE_STATEMENT)
        if refusals:
            lines += [
                "",
                f"**Acquisition refusals: {len(refusals)}**",
                "",
                "These are the sources that were asked and could not answer. They "
                "are listed because an absence of evidence is only interpretable "
                "when the reason for the absence is known.",
                "",
                "| source | operation | category | detail |",
                "|---|---|---|---|",
            ]
            for r in refusals[:40]:
                lines.append(
                    f"| {r.get('source_id')} | {r.get('operation')} | "
                    f"{r.get('category')} | {str(r.get('detail'))[:110]} |"
                )
        if score is not None:
            lines += [
                "",
                "**Scoring dimensions:**",
                "",
                "| dimension | weight | score | scorable | justification / gap |",
                "|---|---|---|---|---|",
            ]
            for d in score.dimensions:
                lines.append(
                    f"| {d.key.value} | {d.weight} | {d.score} | "
                    f"{'yes' if d.scorable else 'NO'} | "
                    f"{(d.justification or d.gap or '')[:110]} |"
                )
            lines += [
                "",
                f"- attractiveness (weighted, excludes evidence quality): {score.attractiveness}",
                f"- evidence quality (reported separately): {score.evidence_quality}",
                f"- coverage of the scoring dimensions: {score.coverage_pct}%",
                f"- unscored dimensions: {', '.join(score.unscored_dimensions) or 'none'}",
            ]
        return "\n".join(lines)

    # ------------------------------------------------------------------ #
    def generate(
        self,
        opportunity: Opportunity,
        *,
        outcome: ScoringOutcome | None = None,
        market: MarketAssessment | None = None,
        competitors: CompetitorAssessment | None = None,
        business_model: BusinessModelAnalysis | None = None,
        commercial: CommercialAssessment | None = None,
        distribution: DistributionAssessment | None = None,
        risk: RiskAssessment | None = None,
        evidence: Sequence[SourceEvidence] = (),
        refusals: Sequence[dict[str, Any]] = (),
        is_test_data: bool = True,
    ):
        """Produce the report.  All nine sections are always present."""
        from app.opportunities.schemas import OpportunityReport

        currency = (
            opportunity.budget.currency if opportunity.budget is not None else "USD"
        )
        sections = {
            ReportSection.A_EXECUTIVE_SUMMARY: self.section_a(opportunity, outcome, currency=currency),
            ReportSection.B_OPPORTUNITY_DESCRIPTION: self.section_b(opportunity),
            ReportSection.C_MARKET_ANALYSIS: self.section_c(market),
            ReportSection.D_COMPETITIVE_ANALYSIS: self.section_d(competitors),
            ReportSection.E_BUSINESS_MODEL: self.section_e(business_model),
            ReportSection.F_COMMERCIAL_FEASIBILITY: self.section_f(commercial, currency=currency),
            ReportSection.G_DISTRIBUTION_AND_ACQUISITION: self.section_g(distribution),
            ReportSection.H_RISK_AND_COMPLIANCE: self.section_h(risk),
            ReportSection.I_EVIDENCE_AND_VALIDATION: self.section_i(
                evidence, opportunity.validation, outcome.score if outcome else None, refusals=refusals
            ),
        }
        classification = (
            outcome.final_classification
            if outcome is not None
            else FinalClassification.INSUFFICIENT_EVIDENCE
        )
        headline = {
            "final_classification": classification.value,
            "lifecycle_state": opportunity.state.value,
            "attractiveness": str(outcome.score.attractiveness) if outcome else "not scored",
            "evidence_quality": str(outcome.score.evidence_quality) if outcome else "not scored",
            "evidence_coverage_pct": str(outcome.score.coverage_pct) if outcome else "0",
            "validation_level": str(opportunity.validation.level.value),
            "evidence_records": str(len(evidence)),
            "acquisition_refusals": str(len(refusals)),
            "commercial_verdict": commercial.verdict if commercial else "not assessed",
            "risk_verdict": risk.verdict if risk else "not assessed",
            "market_verdict": market.verdict if market else "not assessed",
            "competitive_verdict": competitors.verdict if competitors else "not assessed",
            "distribution_verdict": distribution.verdict if distribution else "not assessed",
            "budget_was_modified": "no",
        }
        return OpportunityReport(
            opportunity_id=opportunity.opportunity_id,
            title=f"Opportunity report: {opportunity.candidate.title}",
            final_classification=classification,
            sections=sections,
            headline_metrics=headline,
            evidence_index=tuple(
                {
                    "evidence_id": e.evidence_id,
                    "type": e.evidence_type.value,
                    "classification": e.classification.value,
                    "reliability": e.reliability.value,
                    "source_id": e.source_id,
                }
                for e in evidence
            ),
            refusals=tuple(refusals),
            assumptions=opportunity.assumptions,
            score=outcome.score if outcome else None,
            validation=opportunity.validation,
            is_test_data=is_test_data,
            test_data_notice=self.test_data_notice if is_test_data else None,
            generated_at=datetime.now(timezone.utc),
        )

    @staticmethod
    def to_markdown(report) -> str:
        """Render the report as a single markdown document."""
        parts = [
            f"# {report.title}",
            "",
            f"Report id: `{report.report_id}`  ",
            f"Opportunity id: `{report.opportunity_id}`  ",
            f"Generated: {report.generated_at.isoformat()}  ",
            f"Final classification: **{report.final_classification.value.replace('_', ' ').upper()}**",
            "",
        ]
        if report.is_test_data:
            parts += [
                "> " + (report.test_data_notice or TEST_DATA_NOTICE).replace(". ", ".\n> "),
                "",
            ]
        parts += ["## Headline metrics", ""]
        parts += [f"- **{k.replace('_', ' ')}:** {v}" for k, v in report.headline_metrics.items()]
        parts += [""]
        for section in ReportSection:
            parts += ["---", "", report.sections[section], ""]
        return "\n".join(parts)
